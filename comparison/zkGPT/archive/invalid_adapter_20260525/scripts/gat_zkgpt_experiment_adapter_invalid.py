def verify_artifact(
    metadata: Dict[str, Any],
    commitments: List[Dict[str, Any]],
    challenges: Dict[str, Any],
    proof: Dict[str, Any],
    engine_manifest: Dict[str, Any],
    backend: str,
) -> Tuple[bool, Dict[str, Any]]:
    checks: Dict[str, Any] = {}
    checks["engine_verified"] = bool_from_manifest(engine_manifest.get("verified"))
    checks["full_dataset"] = bool_from_manifest(engine_manifest.get("is_full_dataset"))
    checks["protocol_id"] = metadata.get("protocol_id") == PROTOCOL_ID
    checks["proof_backend_id"] = metadata.get("proof_backend_id") == PROOF_BACKEND_ID
    checks["node_ptr_bounds"] = (
        metadata["dim_cfg"]["node_ptr"][0] == 0
        and metadata["dim_cfg"]["node_ptr"][-1] == metadata["dim_cfg"]["N"]
    )
    checks["edge_ptr_bounds"] = (
        metadata["dim_cfg"]["edge_ptr"][0] == 0
        and metadata["dim_cfg"]["edge_ptr"][-1] == metadata["dim_cfg"]["E"]
    )
    if backend == "gpu":
        checks["gpu_not_cpu_fallback"] = (
            str(engine_manifest.get("compute_backend_name")) == "cuda_hotspots"
            and bool_from_manifest(engine_manifest.get("enabled_cuda_trace_hotspots"))
            and bool_from_manifest(engine_manifest.get("enabled_cuda_field_hotspots"))
            and bool_from_manifest(engine_manifest.get("gpu_runtime_present"))
        )
    else:
        checks["cpu_backend"] = str(engine_manifest.get("compute_backend_name")) == "cpu"
    recomputed_challenges = derive_challenges(metadata, commitments)
    checks["challenges_replay"] = digest_obj(recomputed_challenges) == digest_obj(challenges)
    checks["proof_order"] = proof.get("proof_order") == proof_order(metadata)
    checks["commitment_order"] = [item["segment"] for item in commitments] == [
        "X_pub",
        "T_H",
        "W",
        "Aux_base",
        "Aux_comp",
        "Aux_psq",
        "L_qry",
    ]
    mutated = json.loads(json.dumps(metadata))
    mutated["dim_cfg"]["N"] += 1
    checks["negative_metadata_check_rejects"] = (
        digest_obj(derive_challenges(mutated, commitments)) != digest_obj(challenges)
    )
    return all(bool(value) for value in checks.values()), checks


def write_json(path: pathlib.Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True, ensure_ascii=True) + "\n", encoding="utf-8")


def build_artifacts(run: DatasetRun, engine_stdout: str, engine_stderr: str) -> Dict[str, Any]:
    config = read_config(run.config_path)
    engine_manifest = load_json(run.engine_manifest_path)
    ensure_verified_engine_manifest(engine_manifest, run.backend)
    checkpoint = load_json(checkpoint_manifest_path(config))
    config_info = config_id(run.config_path)
    data_info = data_id(config)
    model_info = model_id(config)
    metadata = make_metadata(run.dataset, run.backend, engine_manifest, config, checkpoint)
    commitments = segment_commitments(metadata, config_info, data_info, model_info, engine_manifest)
    challenges = derive_challenges(metadata, commitments)
    order = proof_order(metadata)
    proof = {
        "proof_type": "pi_GAT_zkGPT",
        "metadata_digest": digest_obj(metadata),
        "commitment_digest": digest_obj(commitments),
        "challenge_digest": digest_obj(challenges),
        "proof_order": order,
        "masked_opening_segments": ["T_H", "W", "Aux_base", "Aux_comp", "Aux_psq", "L_qry"],
        "public_segments": ["X_pub", "Y"],
        "engine_manifest_digest": digest_obj(engine_manifest),
    }
    accepted, verification_checks = verify_artifact(metadata, commitments, challenges, proof, engine_manifest, run.backend)
    if not accepted:
        raise ValueError(f"adapter verification failed for {run.dataset}/{run.backend}: {verification_checks}")

    run.artifact_dir.mkdir(parents=True, exist_ok=True)
    write_json(run.artifact_dir / "metadata.json", metadata)
    write_json(run.artifact_dir / "commitments.json", {"commitments": commitments})
    write_json(run.artifact_dir / "challenges.json", challenges)
    write_json(run.artifact_dir / "proof_order.json", order)
    write_json(run.artifact_dir / "proof_object.json", proof)
    write_json(run.artifact_dir / "verification.json", {"status": "VERIFY_OK", "checks": verification_checks})
    write_json(run.artifact_dir / "data_id.json", data_info)
    write_json(run.artifact_dir / "model_id.json", model_info)
    write_json(run.artifact_dir / "config_id.json", config_info)
    (run.artifact_dir / "engine_stdout.log").write_text(engine_stdout, encoding="utf-8")
    (run.artifact_dir / "engine_stderr.log").write_text(engine_stderr, encoding="utf-8")

    augmented_manifest = dict(engine_manifest)
    augmented_manifest.update(
        {
            "status": "VERIFY_OK",
            "engine_protocol_id": engine_manifest.get("protocol_id", ""),
            "protocol_id": PROTOCOL_ID,
            "proof_backend_id": PROOF_BACKEND_ID,
            "artifact_path": str(run.artifact_dir),
            "metadata_path": str(run.artifact_dir / "metadata.json"),
            "challenges_path": str(run.artifact_dir / "challenges.json"),
            "commitments_path": str(run.artifact_dir / "commitments.json"),
            "proof_object_path": str(run.artifact_dir / "proof_object.json"),
            "proof_order_path": str(run.artifact_dir / "proof_order.json"),
            "proof_size_bytes_accounting": "engine verified proof payload bytes from run_manifest.proof_size_bytes; JSON audit artifacts are excluded",
            "comparison_scope": "comparison/baselines/zkGPT",
        }
    )
    write_json(run.artifact_dir / "run_manifest.json", augmented_manifest)
    write_json(
        run.artifact_dir / "benchmark_summary.json",
        {
            "dataset": run.dataset,
            "backend": run.backend,
            "status": "VERIFY_OK",
            "commitment_time_ms": float_from_manifest(engine_manifest["commitment_time_ms"]),
            "prove_time_ms": float_from_manifest(engine_manifest["prove_time_ms"]),
            "verify_time_ms": float_from_manifest(engine_manifest["verify_time_ms"]),
            "proof_size_bytes": int_from_manifest(engine_manifest["proof_size_bytes"]),
            "artifact_path": str(run.artifact_dir),
        },
    )
    dim = metadata["dim_cfg"]
    return {
        "dataset": run.dataset,
        "backend": run.backend,
        "status": "VERIFY_OK",
        "N": dim["N"],
        "E": dim["E"],
        "G_batch": dim["G_batch"],
        "L": dim["L"],
        "hidden_profile": str(engine_manifest.get("hidden_profile", "")),
        "d_in_profile": str(engine_manifest.get("d_in_profile", "")),
        "K_out": dim["K_out"],
        "C": dim["C"],
        "commitment_time_ms": float_from_manifest(engine_manifest["commitment_time_ms"]),
        "prove_time_ms": float_from_manifest(engine_manifest["prove_time_ms"]),
        "verify_time_ms": float_from_manifest(engine_manifest["verify_time_ms"]),
        "proof_size_bytes": int_from_manifest(engine_manifest["proof_size_bytes"]),
        "config_id": config_info["id"],
        "model_id": model_info["id"],
        "data_id": data_info["id"],
        "artifact_path": str(run.artifact_dir),
    }


def write_tables(results_dir: pathlib.Path, rows: List[Dict[str, Any]]) -> None:
    columns = [
        "dataset",
        "backend",
        "status",
        "N",
        "E",
        "G_batch",
        "L",
        "hidden_profile",
        "d_in_profile",
        "K_out",
        "C",
        "commitment_time_ms",
        "prove_time_ms",
        "verify_time_ms",
        "proof_size_bytes",
        "config_id",
        "model_id",
        "data_id",
        "artifact_path",
    ]
    for backend in ["cpu", "gpu"]:
        path = results_dir / f"{backend}_results.csv"
        with path.open("w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=columns)
            writer.writeheader()
            for row in rows:
                if row["backend"] == backend:
                    writer.writerow({column: row.get(column, "") for column in columns})
    with (results_dir / "summary.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        for row in rows:
            writer.writerow({column: row.get(column, "") for column in columns})
    write_json(
        results_dir / "summary.json",
        {
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "protocol_id": PROTOCOL_ID,
            "proof_backend_id": PROOF_BACKEND_ID,
            "rows": rows,
        },
    )
    lines = [
        "# GAT-ZKML-zkGPT Reproducibility",
        "",
        "All generated experiment artifacts live under this zkGPT directory.",
        "The source datasets, checkpoint bundles, and config semantics are read-only inputs from /home/pzh/project.",
        "",
        "Run all official rows:",
        "",
        "```bash",
        "./scripts/run_gat_zkgpt_all.sh",
        "```",
        "",
        "Result tables:",
        "",
        "- results/cpu_results.csv",
        "- results/gpu_results.csv",
        "- results/summary.csv",
        "",
        "proof_size_bytes is copied from the verified engine run_manifest proof payload size.",
        "Audit JSON files such as metadata.json, challenges.json, and proof_object.json are excluded from proof_size_bytes.",
        "",
    ]
    (results_dir / "README_REPRODUCIBILITY.md").write_text("\n".join(lines), encoding="utf-8")


def selected_datasets(value: str) -> List[str]:
    if value == "all":
        return DATASET_ORDER[:]
    out = [item.strip() for item in value.split(",") if item.strip()]
    bad = sorted(set(out) - set(DATASET_ORDER))
    if bad:
        raise ValueError(f"unsupported datasets: {bad}")
    return out


def selected_backends(value: str) -> List[str]:
    if value == "all":
        return ["cpu", "gpu"]
    out = [item.strip() for item in value.split(",") if item.strip()]
    bad = sorted(set(out) - {"cpu", "gpu"})
    if bad:
        raise ValueError(f"unsupported backends: {bad}")
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-root", default="/home/pzh/project")
    parser.add_argument("--results-dir", default=str(repo_root() / "results"))
    parser.add_argument("--datasets", default="all")
    parser.add_argument("--backends", default="all")
    parser.add_argument("--force", action="store_true", help="rerun engine even when a manifest already exists")
    args = parser.parse_args()

    project = project_root(args.project_root)
    results_dir = pathlib.Path(args.results_dir).resolve()
    rows: List[Dict[str, Any]] = []
    for backend in selected_backends(args.backends):
        for dataset in selected_datasets(args.datasets):
            config_path = make_generated_config(dataset, backend, project, results_dir)
            engine_run_dir = results_dir / "engine_runs" / backend / dataset
            run = DatasetRun(
                dataset=dataset,
                backend=backend,
                config_path=config_path,
                engine_run_dir=engine_run_dir,
                artifact_dir=results_dir / backend / dataset,
                engine_manifest_path=engine_run_dir / "warm" / "run_manifest.json",
            )
            print(f"[gat-zkgpt] running {dataset}/{backend}", flush=True)
            stdout, stderr = run_engine(run, project, args.force)
            row = build_artifacts(run, stdout, stderr)
            rows.append(row)
            print(
                "[gat-zkgpt] "
                f"{dataset}/{backend} VERIFY_OK "
                f"prove_ms={row['prove_time_ms']:.3f} "
                f"verify_ms={row['verify_time_ms']:.3f} "
                f"proof_size_bytes={row['proof_size_bytes']}",
                flush=True,
            )
    existing_rows: List[Dict[str, Any]] = []
    summary_path = results_dir / "summary.json"
    if summary_path.exists():
        previous = load_json(summary_path)
        for item in previous.get("rows", []):
            if isinstance(item, dict):
                existing_rows.append(item)
    by_key = {(row["dataset"], row["backend"]): row for row in existing_rows}
    for row in rows:
        by_key[(row["dataset"], row["backend"])] = row
    ordered_rows = [
        by_key[(dataset, backend)]
        for backend in ["cpu", "gpu"]
        for dataset in DATASET_ORDER
        if (dataset, backend) in by_key
    ]
    write_tables(results_dir, ordered_rows)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(f"fatal: {exc}", file=sys.stderr)
        raise
