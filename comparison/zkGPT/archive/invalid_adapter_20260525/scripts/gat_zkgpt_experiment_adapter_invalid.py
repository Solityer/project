def segment_commitments(
    metadata: Dict[str, Any],
    config_info: Dict[str, Any],
    data_info: Dict[str, Any],
    model_info: Dict[str, Any],
    engine_manifest: Dict[str, Any],
) -> List[Dict[str, Any]]:
    base_seed = digest_obj(
        {
            "metadata": metadata,
            "config": config_info["id"],
            "data": data_info["id"],
            "model": model_info["id"],
            "engine_manifest": digest_obj(engine_manifest),
        }
    )
    segment_payloads = {
        "X_pub": {
            "metadata": metadata["dim_cfg"],
            "batching_rule": metadata["batching_rule"],
            "edge_sort_rule": metadata["edge_sort_rule"],
        },
        "T_H": data_info,
        "W": model_info,
        "Aux_base": {
            "forward_ms": engine_manifest.get("forward_ms"),
            "trace_generation_ms": engine_manifest.get("trace_generation_ms"),
            "hidden_profile": metadata["dim_cfg"]["hidden_profile"],
            "output_rule": "attention-head-bias-then-average",
        },
        "Aux_comp": {
            "depends_on": ["xi_l_r", "xi_cat_l", "xi_out"],
            "source": digest_obj(engine_manifest),
        },
        "Aux_psq": {
            "depends_on": ["lambda_psq_l_r", "lambda_psq_out_s"],
            "batch_aware_grouping": True,
            "source": digest_obj({"node_ptr": metadata["dim_cfg"]["node_ptr"], "edge_ptr": metadata["dim_cfg"]["edge_ptr"]}),
        },
        "L_qry": {
            "families": [
                "hidden_range",
                "output_range",
                "hidden_lrelu",
                "output_lrelu",
                "hidden_elu",
                "hidden_exp",
                "output_exp",
                "rescale_rounding_range",
            ],
            "lasso_cfg_id": LASSO_CFG_ID,
        },
    }
    order = ["X_pub", "T_H", "W", "Aux_base", "Aux_comp", "Aux_psq", "L_qry"]
    commitments: List[Dict[str, Any]] = []
    for index, name in enumerate(order):
        payload_digest = digest_obj(segment_payloads[name])
        blinding_id = sha256_text(f"{base_seed}:{index}:{name}:masked-opening")
        commitments.append(
            {
                "segment": name,
                "order": index,
                "payload_digest": payload_digest,
                "hiding_randomness_id": blinding_id,
                "commitment": sha256_text(f"zkPC.Commit:{name}:{payload_digest}:{blinding_id}"),
                "opening_mode": "OpenMasked" if name != "X_pub" else "public-local-eval",
            }
        )
    return commitments


def derive_challenges(metadata: Dict[str, Any], commitments: List[Dict[str, Any]]) -> Dict[str, Any]:
    transcript: List[Dict[str, Any]] = []

    def squeeze(label: str, payload: Any) -> str:
        state = digest_obj({"label": label, "payload": payload, "transcript": transcript})
        transcript.append({"label": label, "challenge": state})
        return state

    base_commitments = [item for item in commitments if item["segment"] in {"W", "T_H", "Aux_base"}]
    comp_commitment = [item for item in commitments if item["segment"] == "Aux_comp"]
    psq_qry_commitments = [item for item in commitments if item["segment"] in {"Aux_psq", "L_qry"}]
    dim = metadata["dim_cfg"]
    hidden = dim["hidden_profile"]
    out: Dict[str, Any] = {
        "transcript_domain_order": [
            "gat-zkgpt/meta",
            "gat-zkgpt/model-commit",
            "gat-zkgpt/static-table",
            "gat-zkgpt/input-commit",
            "gat-zkgpt/lasso",
            "gat-zkgpt/matmul",
            "gat-zkgpt/gkr",
            "gat-zkgpt/open",
        ],
        "compression": {},
        "psq": {},
        "lasso": {},
        "matmul": {},
        "gkr": {},
        "open": {},
    }
    squeeze("gat-zkgpt/meta", metadata)
    squeeze("gat-zkgpt/model-commit", base_commitments)
    for layer_index, layer in enumerate(hidden, start=1):
        for head_index in range(layer["head_count"]):
            out["compression"][f"xi_l{layer_index}_h{head_index}"] = squeeze(
                f"xi/layer/{layer_index}/head/{head_index}",
                base_commitments,
            )
        out["compression"][f"xi_cat_l{layer_index}"] = squeeze(f"xi/cat/{layer_index}", base_commitments)
    out["compression"]["xi_out"] = squeeze("xi/out", base_commitments)
    squeeze("gat-zkgpt/input-commit/comp", comp_commitment)
    for layer_index, layer in enumerate(hidden, start=1):
        for head_index in range(layer["head_count"]):
            out["psq"][f"lambda_psq_l{layer_index}_h{head_index}"] = squeeze(
                f"lambda/psq/layer/{layer_index}/head/{head_index}",
                comp_commitment,
            )
    for head_index in range(dim["K_out"]):
        out["psq"][f"lambda_psq_out_h{head_index}"] = squeeze(f"lambda/psq/out/{head_index}", comp_commitment)
    squeeze("gat-zkgpt/input-commit/psq-qry", psq_qry_commitments)
    for family in [
        "hidden_range",
        "output_range",
        "hidden_lrelu",
        "output_lrelu",
        "hidden_elu",
        "hidden_exp",
        "output_exp",
        "rescale_rounding_range",
    ]:
        out["lasso"][f"eta_{family}"] = squeeze(f"lasso/{family}", psq_qry_commitments)
    out["matmul"]["rho_matmul"] = squeeze("matmul/sumcheck", commitments)
    out["gkr"]["rho_gkr"] = squeeze("gkr/layered-sumcheck", commitments)
    out["open"]["rho_combine"] = squeeze("open/combine", commitments)
    out["open"]["rho_masked_open"] = squeeze("open/masked", commitments)
    out["transcript"] = transcript
    return out


def proof_order(metadata: Dict[str, Any]) -> Dict[str, Any]:
    hidden = metadata["dim_cfg"]["hidden_profile"]
    k_out = metadata["dim_cfg"]["K_out"]
    lasso_order: List[str] = []
    for layer_index, layer in enumerate(hidden, start=1):
        for head_index in range(layer["head_count"]):
            lasso_order.append(f"hidden_range/l{layer_index}/h{head_index}")
    for head_index in range(k_out):
        lasso_order.append(f"output_range/h{head_index}")
