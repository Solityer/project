from __future__ import annotations

import pathlib
import re
from dataclasses import dataclass
from typing import Dict, List

from .constants import CONFIG_BY_DATASET, CONFIG_DATASET_VALUE


@dataclass(frozen=True)
class HiddenShape:
    head_count: int
    head_dim: int


@dataclass(frozen=True)
class AppConfig:
    entries: Dict[str, str]
    path: pathlib.Path
    project_root: pathlib.Path

    @property
    def dataset(self) -> str:
        return self.entries["dataset"]

    @property
    def cache_dir(self) -> pathlib.Path:
        return self.project_root / self.entries.get("cache_root", "data/cache") / self.dataset

    @property
    def checkpoint_bundle(self) -> pathlib.Path:
        raw = pathlib.Path(self.entries["checkpoint_bundle"])
        return raw if raw.is_absolute() else self.project_root / raw

    @property
    def range_bits(self) -> int:
        return int(self.entries.get("range_bits", "12"))

    @property
    def batch_graphs(self) -> int:
        return int(self.entries.get("batch_graphs", "1"))

    @property
    def hidden_profile(self) -> List[HiddenShape]:
        return parse_hidden_profile(self.entries.get("hidden_profile", ""))

    @property
    def d_in_profile(self) -> List[int]:
        return parse_int_list(self.entries.get("d_in_profile", ""))

    @property
    def layer_count(self) -> int:
        return int(self.entries.get("L", str(len(self.hidden_profile) + 1)))

    @property
    def k_out(self) -> int:
        return int(self.entries.get("K_out", "1"))

    @property
    def num_classes(self) -> int:
        return int(self.entries.get("num_classes", "0"))

    @property
    def symmetrize_edges(self) -> bool:
        return self.entries.get("symmetrize_edges", "false").lower() == "true"

    @property
    def deduplicate_edges(self) -> bool:
        return self.entries.get("deduplicate_edges", "true").lower() != "false"


def read_config(path: pathlib.Path) -> Dict[str, str]:
    out: Dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if "=" not in line:
            raise ValueError(f"invalid config line in {path}: {raw}")
        key, value = line.split("=", 1)
        out[key.strip()] = value.strip()
    return out


def write_config(path: pathlib.Path, entries: Dict[str, str]) -> None:
    order = [
        "dataset",
        "data_root",
        "cache_root",
        "export_dir",
        "checkpoint_bundle",
        "reference_output_dir",
        "task_type",
        "report_unit",
        "batching_rule",
        "self_loop_rule",
        "edge_sort_rule",
        "chunking_rule",
        "L",
        "hidden_profile",
        "d_in_profile",
        "K_out",
        "batch_graphs",
        "hidden_dim",
        "num_classes",
        "range_bits",
        "seed",
        "allow_synthetic_model",
        "dump_trace",
        "auto_prepare_dataset",
        "model_arch_id",
        "model_param_id",
        "quant_cfg_id",
        "static_table_id",
        "degree_bound_id",
        "symmetrize_edges",
        "deduplicate_edges",
    ]
    lines = ["# Generated by the independent zkGPT baseline runner."]
    for key in order:
        if key in entries:
            lines.append(f"{key} = {entries[key]}")
    for key in sorted(entries):
        if key not in order:
            lines.append(f"{key} = {entries[key]}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_hidden_profile(value: str) -> List[HiddenShape]:
    out: List[HiddenShape] = []
    for token in re.sub(r"[\[\]\s]", "", value).split(","):
        if not token:
            continue
        left, right = re.split("[xX]", token, maxsplit=1)
        out.append(HiddenShape(int(left), int(right)))
    return out


def parse_int_list(value: str) -> List[int]:
    text = re.sub(r"[\[\]\s]", "", str(value))
    return [int(part) for part in text.split(",") if part]


def generated_config(dataset: str, backend: str, project_root: pathlib.Path, zk_root: pathlib.Path) -> pathlib.Path:
    source = project_root / "configs" / CONFIG_BY_DATASET[dataset]
    entries = read_config(source)
    entries["dataset"] = CONFIG_DATASET_VALUE[dataset]
    entries["data_root"] = str(project_root / "data")
    entries["cache_root"] = str(project_root / "data/cache")
    entries["checkpoint_bundle"] = str(project_root / entries["checkpoint_bundle"])
    entries["reference_output_dir"] = str(project_root / entries.get("reference_output_dir", "runs/reference"))
    entries["export_dir"] = str(zk_root / "results" / "runs" / backend / dataset)
    entries["auto_prepare_dataset"] = "false"
    out = zk_root / "configs" / "generated" / backend / CONFIG_BY_DATASET[dataset]
    write_config(out, entries)
    return out


def load_app_config(path: pathlib.Path, project_root: pathlib.Path) -> AppConfig:
    return AppConfig(entries=read_config(path), path=path.resolve(), project_root=project_root.resolve())

